import { Money } from '../src/common/value-objects/money.value-object';
import { Wallet, Currency } from '../src/domain/entities/wallet.entity';
import { WagerTransaction, TransactionKind, TransactionStatus } from '../src/domain/entities/wager-transaction.entity';
import { LedgerEntry, LedgerEntryType } from '../src/domain/entities/ledger-entry.entity';
import { OutboxEvent } from '../src/domain/entities/outbox-event.entity';
import { InboxMessage } from '../src/domain/entities/inbox-message.entity';

describe('Architecture Validation', () => {
  describe('Domain Entities', () => {
    it('should create Wallet with correct structure', () => {
      const wallet = Wallet.create('player-123', Currency.BRL);
      expect(wallet.playerId).toBe('player-123');
      expect(wallet.currency).toBe(Currency.BRL);
      expect(wallet.balance.toString()).toBe('0.00');
      expect(wallet.version).toBe(0);
      // id is generated by database (uuid_generate_v4)
    });

    it('should credit and debit wallet correctly', () => {
      const wallet = Wallet.create('player-123', Currency.BRL);
      wallet.credit(Money.fromString('100.00'));
      expect(wallet.balance.toString()).toBe('100.00');

      wallet.debit(Money.fromString('30.00'));
      expect(wallet.balance.toString()).toBe('70.00');
    });

    it('should prevent overdraft', () => {
      const wallet = Wallet.create('player-123', Currency.BRL);
      wallet.credit(Money.fromString('50.00'));
      expect(() => wallet.debit(Money.fromString('100.00'))).toThrow('Insufficient funds');
    });

    it('should track version for optimistic locking', () => {
      const wallet = Wallet.create('player-123', Currency.BRL);
      const initialVersion = wallet.version;
      wallet.credit(Money.fromString('100.00'));
      // Version is incremented by TypeORM on save, not in memory
      // The entity has @VersionColumn() decorator for this
      expect(wallet.version).toBe(initialVersion);
    });
  });

  describe('WagerTransaction Entity', () => {
    it('should create transaction with correct status flow', () => {
      const tx = WagerTransaction.create(
        'wallet-123',
        TransactionKind.BET,
        Money.fromString('50.00'),
        'idem-123'
      );

      expect(tx.status).toBe(TransactionStatus.PENDING);
      expect(tx.idempotencyKey).toBe('idem-123');
    });

    it('should handle PENDING_REFERENCE for REFUND/ROLLBACK', () => {
      const tx = WagerTransaction.create(
        'wallet-123',
        TransactionKind.REFUND,
        Money.fromString('50.00'),
        'idem-123',
        'ref-tx-123'
      );

      expect(tx.status).toBe(TransactionStatus.PENDING);
      expect(tx.referenceTransactionId).toBe('ref-tx-123');
      expect(tx.requiresReference()).toBe(true);
    });

    it('should transition statuses correctly', () => {
      const tx = WagerTransaction.create(
        'wallet-123',
        TransactionKind.BET,
        Money.fromString('50.00'),
        'idem-123'
      );

      tx.markProcessed();
      expect(tx.status).toBe(TransactionStatus.PROCESSED);

      const tx2 = WagerTransaction.create(
        'wallet-123',
        TransactionKind.BET,
        Money.fromString('50.00'),
        'idem-456'
      );

      tx2.markRejected();
      expect(tx2.status).toBe(TransactionStatus.REJECTED);
    });

    it('should identify credit/debit/no-ledger transactions', () => {
      const bet = WagerTransaction.create('wallet-123', TransactionKind.BET, Money.fromString('50.00'), 'idem-1');
      const win = WagerTransaction.create('wallet-123', TransactionKind.WIN, Money.fromString('100.00'), 'idem-2');
      const loss = WagerTransaction.create('wallet-123', TransactionKind.LOSS, Money.fromString('50.00'), 'idem-3');
      const refund = WagerTransaction.create('wallet-123', TransactionKind.REFUND, Money.fromString('50.00'), 'idem-4');
      const opening = WagerTransaction.create('wallet-123', TransactionKind.OPENING, Money.fromString('100.00'), 'idem-5');

      expect(bet.isDebit()).toBe(true);
      expect(bet.isCredit()).toBe(false);
      expect(bet.isNoLedger()).toBe(false);

      expect(win.isCredit()).toBe(true);
      expect(win.isDebit()).toBe(false);

      expect(loss.isNoLedger()).toBe(true);
      expect(loss.isDebit()).toBe(false);
      expect(loss.isCredit()).toBe(false);

      expect(refund.isCredit()).toBe(true);
      expect(refund.requiresReference()).toBe(true);

      expect(opening.isCredit()).toBe(true);
    });
  });

  describe('LedgerEntry Entity', () => {
    it('should create debit entry', () => {
      const entry = LedgerEntry.create(
        'wallet-123',
        'tx-123',
        LedgerEntryType.DEBIT,
        Money.fromString('50.00'),
        Money.fromString('100.00'),
        Money.fromString('50.00'),
      );

      expect(entry.entryType).toBe(LedgerEntryType.DEBIT);
      expect(entry.amount.toString()).toBe('50.00');
      expect(entry.balanceBefore.toString()).toBe('100.00');
      expect(entry.balanceAfter.toString()).toBe('50.00');
    });

    it('should create credit entry', () => {
      const entry = LedgerEntry.create(
        'wallet-123',
        'tx-123',
        LedgerEntryType.CREDIT,
        Money.fromString('50.00'),
        Money.fromString('50.00'),
        Money.fromString('100.00'),
      );

      expect(entry.entryType).toBe(LedgerEntryType.CREDIT);
      expect(entry.balanceBefore.toString()).toBe('50.00');
      expect(entry.balanceAfter.toString()).toBe('100.00');
    });
  });

  describe('OutboxEvent Entity', () => {
    it('should create outbox event', () => {
      const event = OutboxEvent.create(
        'WalletCreated',
        { walletId: 'wallet-123', playerId: 'player-123' },
        'wallet-123',
        'Wallet',
        'corr-123'
      );

      expect(event.eventType).toBe('WalletCreated');
      expect(event.processedAt).toBeUndefined(); // Not set until markProcessed
      expect(event.payload).toEqual({ walletId: 'wallet-123', playerId: 'player-123' });
      expect(event.retryCount).toBe(0);
    });

    it('should mark as processed', () => {
      const event = OutboxEvent.create(
        'WalletCreated',
        {},
        'wallet-123',
        'Wallet'
      );

      event.markProcessed();
      expect(event.processedAt).toBeInstanceOf(Date);
    });

    it('should record failure for retry', () => {
      const event = OutboxEvent.create('Test', {}, 'id', 'Type');
      event.recordFailure('Network error');
      expect(event.retryCount).toBe(1);
      expect(event.lastError).toBe('Network error');
    });
  });

  describe('InboxMessage Entity', () => {
    it('should create inbox message for idempotency', () => {
      const msg = InboxMessage.create(
        'api',
        'msg-123',
        { walletId: 'wallet-123', kind: 'BET' },
        'idem-key-123'
      );

      expect(msg.messageId).toBe('msg-123');
      expect(msg.consumerName).toBe('api');
      expect(msg.idempotencyKey).toBe('idem-key-123');
      expect(msg.processedAt).toBeUndefined(); // Not set until markProcessed
      expect(msg.status).toBe('PENDING');
    });

    it('should mark as processed', () => {
      const msg = InboxMessage.create('api', 'msg-123', {});
      msg.markProcessed();
      expect(msg.processedAt).toBeInstanceOf(Date);
      expect(msg.status).toBe('PROCESSED');
    });

    it('should mark as failed', () => {
      const msg = InboxMessage.create('api', 'msg-123', {});
      msg.markFailed('Error message');
      expect(msg.status).toBe('FAILED');
      expect(msg.errorMessage).toBe('Error message');
    });
  });
});

describe('Money Value Object - Financial Correctness', () => {
  it('should never lose precision in chained operations', () => {
    let balance = Money.fromString('1000.00');

    // Simulate many transactions
    for (let i = 0; i < 100; i++) {
      balance = balance.add(Money.fromString('0.01'));
    }

    expect(balance.toString()).toBe('1001.00');
  });

  it('should handle edge cases correctly', () => {
    // Very small amounts
    const small = Money.fromString('0.01');
    expect(small.cents).toBe(1);

    // Large amounts
    const large = Money.fromString('999999999.99');
    expect(large.cents).toBe(99999999999);
  });

  it('should be immutable', () => {
    const a = Money.fromString('100.00');
    const b = Money.fromString('50.00');
    const result = a.add(b);

    expect(a.toString()).toBe('100.00');
    expect(b.toString()).toBe('50.00');
    expect(result.toString()).toBe('150.00');
    expect(result).not.toBe(a);
    expect(result).not.toBe(b);
  });

  it('should enforce exactly 2 decimal places', () => {
    expect(() => Money.fromString('100.555')).toThrow('Invalid money format');
    expect(Money.fromString('100.5').toString()).toBe('100.50');
    expect(Money.fromString('100').toString()).toBe('100.00');
  });
});

describe('Concurrency Control - Pessimistic Locking', () => {
  it('should have walletId as unit of concurrency', () => {
    // The Wallet entity design ensures all balance changes
    // go through credit/debit methods which are called within
    // a transaction that holds a pessimistic lock on the wallet row.
    const wallet = Wallet.create('player-123', Currency.BRL);
    // walletId is the concurrency unit - all operations on same wallet are serialized
    expect(wallet.playerId).toBe('player-123');
    expect(wallet.currency).toBe(Currency.BRL);
  });
});

describe('Idempotency - Consumer-side Deduplication', () => {
  it('should use composite key (messageId + consumerName)', () => {
    const msg1 = InboxMessage.create('api', 'msg-123', {}, 'idem-1');
    const msg2 = InboxMessage.create('sqs-consumer', 'msg-123', {}, 'idem-2');

    // Same messageId, different consumer = different inbox entries
    // This allows same message to be processed by different consumers
    expect(msg1.messageId).toBe(msg2.messageId);
    expect(msg1.consumerName).not.toBe(msg2.consumerName);
  });

  it('should track idempotencyKey separately for payload validation', () => {
    const msg1 = InboxMessage.create('api', 'msg-1', { amount: '100' }, 'idem-same');
    const msg2 = InboxMessage.create('api', 'msg-2', { amount: '200' }, 'idem-same');

    // Different messageId but same idempotencyKey - should be tracked
    // Unique constraint on (consumerName, messageId) prevents duplicate messages
    // idempotencyKey index helps detect same key with different payload
    expect(msg1.idempotencyKey).toBe(msg2.idempotencyKey);
    expect(msg1.messageId).not.toBe(msg2.messageId);
  });
});

describe('Transactional Outbox Pattern', () => {
  it('should create events within same transaction as domain changes', () => {
    const wallet = Wallet.create('player-123', Currency.BRL);
    wallet.credit(Money.fromString('100.00'));

    const event = OutboxEvent.create(
      'WalletCredited',
      { walletId: wallet.id, amount: '100.00' },
      wallet.id,
      'Wallet',
      undefined,
      wallet.id // causationId could be transaction ID
    );

    expect(event.aggregateId).toBe(wallet.id);
    expect(event.eventType).toBe('WalletCredited');
    // causationId is null when undefined is passed (entity sets null for undefined)
    expect(event.causationId).toBeNull();
  });
});

describe('Out-of-Order Handling - PENDING_REFERENCE', () => {
  it('should set PENDING for REFUND/ROLLBACK without reference', () => {
    const refund = WagerTransaction.create(
      'wallet-123',
      TransactionKind.REFUND,
      Money.fromString('50.00'),
      'idem-123'
    );

    // Without referenceTransactionId, stays PENDING
    // The use case will transition to PENDING_REFERENCE if needed
    expect(refund.status).toBe(TransactionStatus.PENDING);
    expect(refund.requiresReference()).toBe(true);
  });

  it('should track referenceTransactionId when provided', () => {
    const refund = WagerTransaction.create(
      'wallet-123',
      TransactionKind.REFUND,
      Money.fromString('50.00'),
      'idem-123',
      'original-bet-id'
    );

    expect(refund.referenceTransactionId).toBe('original-bet-id');
    expect(refund.requiresReference()).toBe(true);
  });

  it('should identify ROLLBACK as requiring reference', () => {
    const rollback = WagerTransaction.create(
      'wallet-123',
      TransactionKind.ROLLBACK,
      Money.fromString('50.00'),
      'idem-123',
      'original-bet-id'
    );

    expect(rollback.requiresReference()).toBe(true);
    expect(rollback.kind).toBe(TransactionKind.ROLLBACK);
  });
});

